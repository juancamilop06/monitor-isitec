-- ===========================================================
-- ROLES: líder de proyecto, trabajador y cliente
-- ===========================================================
alter table public.perfiles add column if not exists tipo text not null default 'trabajador'
  check (tipo in ('lider','trabajador','cliente'));
alter table public.perfiles add column if not exists persona_id text references public.personas(id) on delete set null;
alter table public.perfiles add column if not exists cliente_id text references public.clientes(id) on delete set null;

-- Preguntas del cliente al líder
create table if not exists public.preguntas (
  id               text primary key,
  proyecto_id      text references public.proyectos(id) on delete cascade,
  autor_id         uuid default auth.uid(),
  autor_nombre     text,
  texto            text not null,
  fecha            date default current_date,
  respuesta        text,
  respondida_por   text,
  fecha_respuesta  date,
  estado           text default 'abierta',
  actualizado_en   timestamptz default now(),
  orden            bigint generated by default as identity
);

-- Funciones de apoyo (security definer: no dependen de RLS)
create or replace function public.mi_tipo() returns text
language sql stable security definer set search_path = public as $$
  select coalesce((select tipo from perfiles where id = auth.uid()), 'ninguno')
$$;
create or replace function public.mi_persona() returns text
language sql stable security definer set search_path = public as $$
  select persona_id from perfiles where id = auth.uid()
$$;
create or replace function public.mi_cliente() returns text
language sql stable security definer set search_path = public as $$
  select cliente_id from perfiles where id = auth.uid()
$$;
create or replace function public.es_lider() returns boolean
language sql stable security definer set search_path = public as $$
  select public.mi_tipo() = 'lider'
$$;
-- ¿Este usuario puede ver el proyecto?
create or replace function public.proyecto_visible(pid text) returns boolean
language sql stable security definer set search_path = public as $$
  select case public.mi_tipo()
    when 'lider' then true
    when 'cliente' then exists (select 1 from proyectos where id = pid and cliente_id = public.mi_cliente())
    when 'trabajador' then exists (select 1 from proyectos where id = pid and lider_id = public.mi_persona())
                        or exists (select 1 from tareas where proyecto_id = pid and responsable_id = public.mi_persona())
                        or exists (select 1 from registro_horas where proyecto_id = pid and persona_id = public.mi_persona())
    else false end
$$;

-- El primer usuario registrado queda como líder; los demás eligen trabajador o cliente
create or replace function public.crear_perfil()
returns trigger language plpgsql security definer set search_path = public as $$
declare t text;
begin
  if not exists (select 1 from public.perfiles where tipo = 'lider') then
    t := 'lider';
  else
    t := coalesce(nullif(new.raw_user_meta_data->>'tipo', ''), 'trabajador');
    if t not in ('trabajador', 'cliente') then t := 'trabajador'; end if;
  end if;
  insert into public.perfiles (id, nombre, rol, correo, tipo)
  values (new.id,
          coalesce(new.raw_user_meta_data->>'nombre', split_part(new.email, '@', 1)),
          coalesce(new.raw_user_meta_data->>'rol', case t when 'lider' then 'Líder de proyecto' when 'cliente' then 'Cliente' else 'Miembro del equipo' end),
          new.email, t)
  on conflict (id) do nothing;
  return new;
end $$;

-- Cada usuario completa su vínculo una sola vez (quién es en el equipo / de qué cliente es)
create or replace function public.completar_perfil(p_persona text, p_cliente text, p_nueva_persona text)
returns void language plpgsql security definer set search_path = public as $$
declare yo perfiles; nueva text; ini text;
begin
  select * into yo from perfiles where id = auth.uid();
  if yo.id is null then raise exception 'Perfil no encontrado'; end if;
  if yo.tipo = 'cliente' then
    if yo.cliente_id is null and p_cliente is not null then
      update perfiles set cliente_id = p_cliente where id = yo.id;
    end if;
  else
    if yo.persona_id is null then
      if coalesce(p_nueva_persona, '') <> '' then
        nueva := 'u' || replace(left(yo.id::text, 8), '-', '');
        ini := upper(left(p_nueva_persona, 1) || coalesce(left(split_part(p_nueva_persona, ' ', 2), 1), ''));
        insert into personas (id, nombre, iniciales, color, rol, horas_disponibles)
        values (nueva, p_nueva_persona, ini, 'c-azul', coalesce(yo.rol, 'Miembro del equipo'), 160)
        on conflict (id) do nothing;
        update perfiles set persona_id = nueva where id = yo.id;
      elsif p_persona is not null then
        update perfiles set persona_id = p_persona where id = yo.id;
      end if;
    end if;
  end if;
end $$;

-- El líder asigna o cambia el tipo y el vínculo de cualquier usuario
create or replace function public.asignar_perfil(p_usuario uuid, p_tipo text, p_persona text, p_cliente text)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.es_lider() then raise exception 'Solo un líder puede cambiar accesos'; end if;
  if p_tipo not in ('lider','trabajador','cliente') then raise exception 'Tipo inválido'; end if;
  if p_usuario = auth.uid() and p_tipo <> 'lider'
     and (select count(*) from perfiles where tipo = 'lider') <= 1 then
    raise exception 'Debe quedar al menos un líder';
  end if;
  update perfiles set tipo = p_tipo,
         persona_id = case when p_tipo = 'cliente' then null else p_persona end,
         cliente_id = case when p_tipo = 'cliente' then p_cliente else null end
   where id = p_usuario;
end $$;

grant execute on function public.mi_tipo(), public.mi_persona(), public.mi_cliente(), public.es_lider(),
  public.proyecto_visible(text), public.completar_perfil(text, text, text),
  public.asignar_perfil(uuid, text, text, text) to authenticated;

-- Políticas por rol (reemplazan "equipo_todo")
do $$
declare t text;
begin
  foreach t in array array['personas','clientes','proyectos','tareas','facturas','registro_horas','reportes','alertas_atendidas','preguntas'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "equipo_todo" on public.%I', t);
    execute format('drop policy if exists "leer" on public.%I', t);
    execute format('drop policy if exists "crear" on public.%I', t);
    execute format('drop policy if exists "editar" on public.%I', t);
    execute format('drop policy if exists "borrar" on public.%I', t);
  end loop;
end $$;

-- personas: todos las ven (nombres de responsables); solo el líder las cambia
create policy "leer"   on public.personas for select to authenticated using (true);
create policy "crear"  on public.personas for insert to authenticated with check (public.es_lider());
create policy "editar" on public.personas for update to authenticated using (public.es_lider());
create policy "borrar" on public.personas for delete to authenticated using (public.es_lider());

-- clientes: el cliente solo ve su empresa
create policy "leer"   on public.clientes for select to authenticated
  using (public.mi_tipo() in ('lider','trabajador') or id = public.mi_cliente());
create policy "crear"  on public.clientes for insert to authenticated with check (public.es_lider());
create policy "editar" on public.clientes for update to authenticated using (public.es_lider());
create policy "borrar" on public.clientes for delete to authenticated using (public.es_lider());

-- proyectos: cada quien ve los suyos; solo el líder los cambia
create policy "leer"   on public.proyectos for select to authenticated using (public.proyecto_visible(id));
create policy "crear"  on public.proyectos for insert to authenticated with check (public.es_lider());
create policy "editar" on public.proyectos for update to authenticated using (public.es_lider());
create policy "borrar" on public.proyectos for delete to authenticated using (public.es_lider());

-- tareas: el trabajador crea incidencias o tareas propias y actualiza las suyas; el cliente solo lee
create policy "leer"   on public.tareas for select to authenticated using (public.proyecto_visible(proyecto_id));
create policy "crear"  on public.tareas for insert to authenticated with check (
  public.es_lider() or (public.mi_tipo() = 'trabajador' and public.proyecto_visible(proyecto_id)
                        and (es_incidencia or responsable_id = public.mi_persona())));
create policy "editar" on public.tareas for update to authenticated
  using (public.es_lider() or (public.mi_tipo() = 'trabajador' and responsable_id = public.mi_persona()))
  with check (public.es_lider() or (public.mi_tipo() = 'trabajador' and responsable_id = public.mi_persona()));
create policy "borrar" on public.tareas for delete to authenticated using (public.es_lider());

-- facturas: líder todo; el cliente ve las de sus proyectos; el trabajador no las ve
create policy "leer"   on public.facturas for select to authenticated
  using (public.es_lider() or (public.mi_tipo() = 'cliente' and public.proyecto_visible(proyecto_id)));
create policy "crear"  on public.facturas for insert to authenticated with check (public.es_lider());
create policy "editar" on public.facturas for update to authenticated using (public.es_lider());
create policy "borrar" on public.facturas for delete to authenticated using (public.es_lider());

-- registro de horas: líder todo; el trabajador ve y registra las suyas
create policy "leer"   on public.registro_horas for select to authenticated
  using (public.es_lider() or persona_id = public.mi_persona());
create policy "crear"  on public.registro_horas for insert to authenticated
  with check (public.es_lider() or persona_id = public.mi_persona());
create policy "editar" on public.registro_horas for update to authenticated using (public.es_lider());
create policy "borrar" on public.registro_horas for delete to authenticated using (public.es_lider());

-- reportes: cualquiera exporta; el líder ve todo el historial
create policy "leer"   on public.reportes for select to authenticated
  using (public.es_lider() or actualizado_por = auth.uid());
create policy "crear"  on public.reportes for insert to authenticated with check (true);
create policy "borrar" on public.reportes for delete to authenticated using (public.es_lider());

-- alertas atendidas: solo el líder
create policy "leer"   on public.alertas_atendidas for select to authenticated using (public.es_lider());
create policy "crear"  on public.alertas_atendidas for insert to authenticated with check (public.es_lider());
create policy "borrar" on public.alertas_atendidas for delete to authenticated using (public.es_lider());

-- preguntas: el cliente pregunta sobre sus proyectos; el líder responde
create policy "leer"   on public.preguntas for select to authenticated
  using (public.es_lider() or (public.mi_tipo() = 'cliente' and public.proyecto_visible(proyecto_id)));
create policy "crear"  on public.preguntas for insert to authenticated
  with check (public.es_lider() or (public.mi_tipo() = 'cliente' and public.proyecto_visible(proyecto_id)));
create policy "editar" on public.preguntas for update to authenticated using (public.es_lider());
create policy "borrar" on public.preguntas for delete to authenticated using (public.es_lider());

-- perfiles: cada quien ve el suyo; el líder ve todos. Nadie se cambia el tipo a sí mismo
drop policy if exists "perfiles_leer" on public.perfiles;
drop policy if exists "perfiles_editar_propio" on public.perfiles;
drop policy if exists "perfiles_crear_propio" on public.perfiles;
create policy "perfiles_leer" on public.perfiles for select to authenticated
  using (id = auth.uid() or public.es_lider());

grant select, insert, update, delete on public.preguntas to authenticated;
do $$ begin
  alter publication supabase_realtime add table public.preguntas;
exception when duplicate_object then null; end $$;

-- Usuarios que ya existían antes de los roles: el más antiguo queda como líder
update public.perfiles set tipo = 'lider'
 where id = (select id from public.perfiles order by creado_en limit 1)
   and not exists (select 1 from public.perfiles where tipo = 'lider');

notify pgrst, 'reload schema';
