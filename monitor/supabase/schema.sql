-- Perfil de cada usuario registrado (se crea solo al registrarse)
create table if not exists public.perfiles (
  id         uuid primary key references auth.users(id) on delete cascade,
  nombre     text not null default '',
  rol        text not null default 'Miembro del equipo',
  correo     text,
  creado_en  timestamptz not null default now()
);

create table if not exists public.personas (
  id                text primary key,
  nombre            text not null,
  iniciales         text,
  color             text,
  rol               text,
  horas_disponibles integer default 160
);

create table if not exists public.clientes (
  id     text primary key,
  nombre text not null
);

create table if not exists public.proyectos (
  id                text primary key,
  nombre            text not null,
  cliente_id        text references public.clientes(id) on delete set null,
  lider_id          text references public.personas(id) on delete set null,
  inicio            date not null,
  fin_plan          date not null,
  avance_real       integer not null default 0,
  horas_presupuesto integer default 0,
  valor_contrato    bigint default 0,
  costo_planeado    bigint default 0,
  costo_real        bigint default 0
);

create table if not exists public.tareas (
  id             text primary key,
  proyecto_id    text references public.proyectos(id) on delete cascade,
  nombre         text not null,
  responsable_id text references public.personas(id) on delete set null,
  fecha_limite   date,
  prioridad      text default 'media',
  estado         text default 'pendiente',
  riesgo         jsonb,              -- { causa, mitigacion } o null
  es_incidencia  boolean default false,
  fecha_reporte  date,
  fecha_cierre   date,
  horas          double precision default 0
);

create table if not exists public.facturas (
  id          text primary key,
  proyecto_id text references public.proyectos(id) on delete cascade,
  numero      text,
  monto       bigint default 0,
  emision     date,
  vencimiento date,
  estado      text default 'pendiente'
);

create table if not exists public.registro_horas (
  id          text primary key,
  mes         integer default 0,
  persona_id  text references public.personas(id) on delete cascade,
  proyecto_id text references public.proyectos(id) on delete cascade,
  horas       double precision default 0,
  facturable  boolean default true
);

create table if not exists public.reportes (
  id      text primary key,
  fecha   date,
  alcance text,
  formato text,
  interno boolean default false,
  autor   text
);

create table if not exists public.alertas_atendidas (
  id text primary key
);

-- Auditoría mínima: quién y cuándo tocó cada fila
do $$
declare t text;
begin
  foreach t in array array['personas','clientes','proyectos','tareas','facturas','registro_horas','reportes','alertas_atendidas'] loop
    execute format('alter table public.%I add column if not exists actualizado_en timestamptz default now()', t);
    execute format('alter table public.%I add column if not exists actualizado_por uuid default auth.uid()', t);
    execute format('alter table public.%I add column if not exists orden bigint generated by default as identity', t);
  end loop;
end $$;

-- Crear el perfil automáticamente cuando alguien se registra
create or replace function public.crear_perfil()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.perfiles (id, nombre, rol, correo)
  values (new.id,
          coalesce(new.raw_user_meta_data->>'nombre', split_part(new.email, '@', 1)),
          coalesce(new.raw_user_meta_data->>'rol', 'Miembro del equipo'),
          new.email)
  on conflict (id) do nothing;
  return new;
end $$;

drop trigger if exists al_registrarse on auth.users;
create trigger al_registrarse after insert on auth.users
  for each row execute function public.crear_perfil();

-- Seguridad (RLS): solo usuarios con sesión iniciada leen y escriben.
-- Es un espacio de trabajo compartido por todo el equipo.
alter table public.perfiles enable row level security;
drop policy if exists "perfiles_leer" on public.perfiles;
create policy "perfiles_leer" on public.perfiles for select to authenticated using (true);
drop policy if exists "perfiles_editar_propio" on public.perfiles;
create policy "perfiles_editar_propio" on public.perfiles for update to authenticated using (auth.uid() = id);
drop policy if exists "perfiles_crear_propio" on public.perfiles;
create policy "perfiles_crear_propio" on public.perfiles for insert to authenticated with check (auth.uid() = id);

do $$
declare t text;
begin
  foreach t in array array['personas','clientes','proyectos','tareas','facturas','registro_horas','reportes','alertas_atendidas'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "equipo_todo" on public.%I', t);
    execute format('create policy "equipo_todo" on public.%I for all to authenticated using (true) with check (true)', t);
  end loop;
end $$;

-- Tiempo real: que los cambios de un compañero aparezcan en las demás pantallas
do $$
declare t text;
begin
  foreach t in array array['personas','clientes','proyectos','tareas','facturas','registro_horas','reportes','alertas_atendidas'] loop
    begin
      execute format('alter publication supabase_realtime add table public.%I', t);
    exception when duplicate_object then null;
    end;
  end loop;
end $$;

